from pathlib import Path
import csv

import numpy as np
import matplotlib.pyplot as plt


FS = 20_000_000
FC = 2_000_000
PHASE_BITS = 32
LUT_ADDR_BITS = 10
AMP_BITS = 12
NUM_SAMPLES = 400


def build_lut(lut_size, amp_bits):
    amp_max = (1 << (amp_bits - 1)) - 1
    k = np.arange(lut_size)
    angle = 2 * np.pi * k / lut_size
    cos_lut = np.round(np.cos(angle) * amp_max).astype(int)
    sin_lut = np.round(np.sin(angle) * amp_max).astype(int)
    return cos_lut, sin_lut


def run_dds():
    phase_modulus = 1 << PHASE_BITS
    lut_size = 1 << LUT_ADDR_BITS
    phase_step = round(FC / FS * phase_modulus)
    actual_freq = phase_step / phase_modulus * FS

    cos_lut, sin_lut = build_lut(lut_size, AMP_BITS)

    phase = 0
    rows = []
    for n in range(NUM_SAMPLES):
        addr = phase >> (PHASE_BITS - LUT_ADDR_BITS)
        cos_code = int(cos_lut[addr])
        sin_code = int(sin_lut[addr])
        rows.append({
            "n": n,
            "phase": phase,
            "lut_addr": addr,
            "cos_code": cos_code,
            "sin_code": sin_code,
        })
        phase = (phase + phase_step) % phase_modulus

    return rows, phase_step, actual_freq


def main():
    out_dir = Path("outputs/lesson_13")
    out_dir.mkdir(parents=True, exist_ok=True)

    rows, phase_step, actual_freq = run_dds()
    csv_path = out_dir / "dds_nco_samples.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    t = np.array([row["n"] for row in rows]) / FS
    cos_codes = np.array([row["cos_code"] for row in rows])
    sin_codes = np.array([row["sin_code"] for row in rows])
    addr = np.array([row["lut_addr"] for row in rows])
    phase = np.array([row["phase"] for row in rows], dtype=np.uint64)

    fig, axes = plt.subplots(3, 1, figsize=(12, 8), sharex=True)

    axes[0].step(t[:120] * 1e6, addr[:120], where="post")
    axes[0].set_title("DDS LUT address from high phase bits")
    axes[0].set_ylabel("LUT address")
    axes[0].grid(True, alpha=0.3)

    axes[1].plot(t[:120] * 1e6, cos_codes[:120], label="cos LUT output")
    axes[1].plot(t[:120] * 1e6, sin_codes[:120], label="sin LUT output", alpha=0.8)
    axes[1].set_title("Quantized cos/sin generated by DDS")
    axes[1].set_ylabel("12-bit code")
    axes[1].grid(True, alpha=0.3)
    axes[1].legend(loc="upper right")

    axes[2].plot(t[:120] * 1e6, phase[:120] / (1 << PHASE_BITS))
    axes[2].set_title("Phase accumulator wraps around at 1 cycle")
    axes[2].set_xlabel("time (us)")
    axes[2].set_ylabel("phase / 2^32")
    axes[2].grid(True, alpha=0.3)

    fig.tight_layout()
    png_path = out_dir / "dds_nco_demo.png"
    fig.savefig(png_path, dpi=150)

    print("DDS/NCO demo")
    print(f"FS = {FS} Hz")
    print(f"target FC = {FC} Hz")
    print(f"PHASE_BITS = {PHASE_BITS}")
    print(f"LUT_ADDR_BITS = {LUT_ADDR_BITS}")
    print(f"phase_step = {phase_step}")
    print(f"actual_freq = {actual_freq:.6f} Hz")
    print(f"freq_error = {actual_freq - FC:.6f} Hz")
    print(f"CSV written to: {csv_path.resolve()}")
    print(f"PNG written to: {png_path.resolve()}")


if __name__ == "__main__":
    main()
